def _setup_logging() -> logging.Logger:
    ARTIFACTS_DIR.mkdir(parents=True, exist_ok=True)
    for d in (MANIFESTS_DIR, LEDGERS_DIR, CHECKPOINTS_DIR):
        d.mkdir(parents=True, exist_ok=True)

    # Clear stale artifacts from previous runs
    for f in MANIFESTS_DIR.glob("*.json"):
        f.unlink()
    for f in CHECKPOINTS_DIR.glob("step_*.json"):
        f.unlink()
    for f in LEDGERS_DIR.glob("*.jsonl"):
        f.unlink()

    import io
    fmt = "%(asctime)s %(levelname)-8s %(message)s"
    stdout_handler = logging.StreamHandler(
        io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")
        if hasattr(sys.stdout, "buffer") else sys.stdout
    )
    stdout_handler.setFormatter(logging.Formatter(fmt))
    file_handler = logging.FileHandler(LOG_PATH, mode="w", encoding="utf-8")
    file_handler.setFormatter(logging.Formatter(fmt))

    root = logging.getLogger()
    root.setLevel(logging.INFO)
    root.handlers.clear()
    root.addHandler(file_handler)
    root.addHandler(stdout_handler)
    return logging.getLogger("run_demo")


