def _set_seed(seed: int) -> None:
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)


def _doc_to_sequence(doc: Document, shard_id: str) -> SequenceRecord:
    token_ids = TOKENIZER.encode_with_eos(doc.text)
    return SequenceRecord(
        doc_id   = doc.doc_id,
        shard_id = shard_id,
        token_ids = token_ids,
        mode     = TrainingMode.PRETRAIN,
    )


def _build_batch_from_shard(
    shard: Shard,
    step: int,
    policy: PackingPolicy = PackingPolicy.GREEDY,
) -> PackedBatch:
    """Pack one shard into a single PackedBatch."""
    seq = SequenceRecord(
        doc_id    = shard.doc_ids[0] if shard.doc_ids else "unknown",
        shard_id  = shard.shard_id,
        token_ids = shard.token_ids[:SEQ_LEN * 2],
        mode      = TrainingMode.PRETRAIN,
    )
    batches = pack([seq], policy, SEQ_LEN, batch_id_prefix=f"step{step:04d}")
    return batches[0]


def _get_model_phase(step: int) -> str:
    if step < 20:
        return "seed"
    elif step < 40:
        return "general"
    else:
        return "specialisation"


def _restore_optimizer_from_checkpoint(
    optimizer: torch.optim.Adam,
    ckpt: "Checkpoint",
    model: "TinyModel",
) -> None:
    """Delegate to core.trainer.restore_optimizer_state (D16 fix)."""
    restore_optimizer_state(optimizer, ckpt.optimizer_state, model)


# ══════════════════════════════════════════════════════════════════════════════
# Main orchestration
